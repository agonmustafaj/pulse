#!/usr/bin/env node
/**
 * Cloudflare Pages build: copy frontend/ → dist/ and inject API base.
 *
 * Production (Orbit-style): leave PULSE_API_BASE empty so the SPA calls
 * same-origin /api/* served by Cloudflare Pages Functions in functions/.
 * Optionally set PULSE_API_BASE to an absolute FastAPI origin for a split host.
 * Functions live at repo-root functions/ — they are NOT copied into dist/.
 */
import { cpSync, mkdirSync, rmSync, writeFileSync, existsSync, readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const src = join(root, "frontend");
const dist = join(root, "dist");

if (!existsSync(src)) {
  console.error("Missing frontend/ source directory");
  process.exit(1);
}

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });
cpSync(src, dist, { recursive: true });

// Cloudflare Pages expects _headers at output root
const headersSrc = join(src, "public", "_headers");
if (existsSync(headersSrc)) {
  cpSync(headersSrc, join(dist, "_headers"));
}

const apiBase = (process.env.PULSE_API_BASE || process.env.VITE_API_BASE || "").replace(/\/$/, "");
const config = `/* Generated by scripts/build.mjs — do not commit secrets */
window.PULSE_API_BASE = ${JSON.stringify(apiBase)};
`;
writeFileSync(join(dist, "config.js"), config);

// SPA routing for Cloudflare Pages. If PULSE_API_BASE is set, optionally
// proxy /api and /ws via _redirects when PULSE_PAGES_PROXY=1 (same-site paths).
const redirects = [];
if (apiBase && process.env.PULSE_PAGES_PROXY === "1") {
  redirects.push(`/api/*  ${apiBase}/api/:splat  200`);
  redirects.push(`/ws/*   ${apiBase}/ws/:splat   200`);
}
// SPA fallback. Pages Functions for /api/* take precedence over this rewrite.
redirects.push("/*    /index.html   200");
writeFileSync(join(dist, "_redirects"), redirects.join("\n") + "\n");

// Strip placeholder proxy lines from copied frontend/_redirects if present
const copiedRedirects = join(dist, "_redirects");
// already overwritten above

const indexPath = join(dist, "index.html");
let html = readFileSync(indexPath, "utf8");
if (!html.includes("config.js")) {
  html = html.replace("<head>", '<head>\n    <script src="/config.js"></script>');
  writeFileSync(indexPath, html);
}

console.log(`PULSE build OK → dist/ (API base: ${apiBase || "(same-origin / set PULSE_API_BASE)"})`);
